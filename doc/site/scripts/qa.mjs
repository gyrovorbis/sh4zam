#!/usr/bin/env node
// Accessibility (axe-core) and Lighthouse audits of representative pages in dist/.
// Run after `npm run build`: node scripts/qa.mjs [outDir]   (default build/qa/)
// Writes <outDir>/a11y.md and <outDir>/lighthouse.md; exits 1 on axe violations or
// scores below the site's thresholds (a11y/SEO/best-practices >= 95, perf >= 90 mobile).

import fs from 'node:fs';
import { chromium } from 'playwright';
import { AxeBuilder } from '@axe-core/playwright';
import lighthouse from 'lighthouse';
import * as chromeLauncher from 'chrome-launcher';
import { spawn } from 'node:child_process';

const PAGES = ['/', '/api/', '/api/vector/', '/api/xmtrx/shz_xmtrx_load_wxyz_4x4/', '/guides/matrix-transforms/', '/concepts/xmtrx/', '/api/cpp/quat/', '/cheatsheet/'];
const out = process.argv[2] || 'build/qa';
fs.mkdirSync(out, { recursive: true });

// Separate process, so Lighthouse's own work doesn't stall the server and skew timings.
const PORT = 4593;
const server = spawn(process.execPath, ['scripts/serve.mjs', String(PORT)], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 800));
const origin = `http://127.0.0.1:${PORT}`;
let failed = false;

// axe ------------------------------------------------------------------------
const browser = await chromium.launch();
const context = await browser.newContext();
const a11y = ['# Accessibility (axe-core)', '', `WCAG 2.1 A/AA rules, desktop viewport. Generated by \`scripts/qa.mjs\`.`, '', '| Page | Violations | Details |', '| --- | --- | --- |'];
for (const url of PAGES) {
	const page = await context.newPage();
	await page.goto(origin + url, { waitUntil: 'networkidle' });
	const res = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze();
	const v = res.violations;
	if (v.length) failed = true;
	a11y.push(`| \`${url}\` | ${v.length} | ${v.map((x) => `${x.id} (${x.nodes.length})`).join(', ') || 'none'} |`);
	await page.close();
}
await browser.close();
fs.writeFileSync(`${out}/a11y.md`, a11y.join('\n') + '\n');

// Lighthouse -------------------------------------------------------------------
// A fresh Chrome per run, like a one-off `lighthouse <url>` invocation.
const launch = () => chromeLauncher.launch({ chromePath: chromium.executablePath(), chromeFlags: ["--headless=new", "--no-sandbox"] });
const lh = ['# Lighthouse', '', 'Mobile form factor, default simulated throttling, median of 3 runs, served gzip-compressed like a static host. Generated by `scripts/qa.mjs`.', '', '| Page | Performance | Accessibility | Best practices | SEO |', '| --- | --- | --- | --- | --- |'];
for (const url of PAGES.slice(0, 5)) {
	// Median of three runs: simulated throttling makes single runs noisy.
	const runs = [];
	for (let i = 0; i < 3; i++) {
		const chrome = await launch();
		runs.push((await lighthouse(origin + url, { port: chrome.port, output: 'json', logLevel: 'error', onlyCategories: ['performance', 'accessibility', 'best-practices', 'seo'] })).lhr.categories);
		await chrome.kill();
	}
	const s = (k) => runs.map((c) => Math.round(c[k].score * 100)).sort((a, b) => a - b)[1];
	const row = [s('performance'), s('accessibility'), s('best-practices'), s('seo')];
	if (row[0] < 90 || row[1] < 95 || row[2] < 95 || row[3] < 95) failed = true;
	lh.push(`| \`${url}\` | ${row.join(' | ')} |`);
}

fs.writeFileSync(`${out}/lighthouse.md`, lh.join('\n') + '\n');
server.kill();

console.log(a11y.slice(4).join('\n'));
console.log(lh.slice(4).join('\n'));
process.exit(failed ? 1 : 0);
